function deepMerge(base, overlay) {
  if (!overlay || typeof overlay !== "object" || Array.isArray(overlay)) return overlay ?? base;
  const out = { ...base };
  for (const [k, v] of Object.entries(overlay)) {
    if (v && typeof v === "object" && !Array.isArray(v) && base?.[k] && typeof base[k] === "object") {
      out[k] = deepMerge(base[k], v);
    } else {
      out[k] = v;
    }
  }
  return out;
}

for (const locale of LOCALES) {
  const path = join("locales", locale, "customer-app", "portalStructure.json");
  const data = JSON.parse(readFileSync(path, "utf8"));
  const localized = locale === "en" ? en : deepMerge(en, translations[locale]);
  data.portalStructure = data.portalStructure || {};
  data.portalStructure.integrations = data.portalStructure.integrations || {};
  data.portalStructure.integrations.onboarding = localized;
  writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`);
  console.log("updated", locale);
}
